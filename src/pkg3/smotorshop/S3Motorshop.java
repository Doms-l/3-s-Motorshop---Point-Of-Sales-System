    private void loadTransactions(
        String dateFrom,
        String dateTo,
        String type) {

    DefaultTableModel model =
            (DefaultTableModel) transactiontable.getModel();

    model.setRowCount(0);

    StringBuilder sql = new StringBuilder(
        "SELECT " +
        "st.transaction_id, " +
        "st.transaction_date, " +
        "COALESCE(c.full_name, 'Walk-in') AS customer_name, " +
        "st.transaction_type, " +
        "st.total_amount, " +
        "st.amount_paid, " +
        "st.change_amount " +
        "FROM sales_transactions st " +
        "LEFT JOIN customers c ON st.customer_id = c.customer_id " +
        "WHERE 1=1"
    );

    java.util.List<String> params =
            new java.util.ArrayList<>();

    // DATE FROM
    if (dateFrom != null &&
            !dateFrom.trim().isEmpty()) {

        sql.append(
            " AND DATE(st.transaction_date) >= ?"
        );

        params.add(dateFrom);
    }

    // DATE TO
    if (dateTo != null &&
            !dateTo.trim().isEmpty()) {

        sql.append(
            " AND DATE(st.transaction_date) <= ?"
        );

        params.add(dateTo);
    }

    // TRANSACTION TYPE
    if (type != null &&
            !type.trim().isEmpty() &&
            !type.equals("Select:") &&
            !type.equals("All")) {

        sql.append(
            " AND st.transaction_type = ?"
        );

        params.add(type);
    }

    sql.append(
        " ORDER BY st.transaction_date DESC"
    );

    try (Connection con =
                DBConnection.getConnection();
         PreparedStatement ps =
                con.prepareStatement(sql.toString())) {

        for (int i = 0;
             i < params.size();
             i++) {

            ps.setString(
                i + 1,
                params.get(i)
            );
        }

        try (ResultSet rs =
                ps.executeQuery()) {

            int no = 1;

            while (rs.next()) {

                model.addRow(new Object[]{

                    no++,

                    rs.getInt(
                        "transaction_id"
                    ),

                    rs.getTimestamp(
                        "transaction_date"
                    ).toLocalDateTime()
                     .format(DATE_FMT),

                    rs.getString(
                        "customer_name"
                    ),

                    rs.getString(
                        "transaction_type"
                    ),

                    MONEY.format(
                        rs.getDouble(
                            "total_amount"
                        )
                    ),

                    MONEY.format(
                        rs.getDouble(
                            "amount_paid"
                        )
                    ),

                    MONEY.format(
                        rs.getDouble(
                            "change_amount"
                        )
                    ),

                    ""
                });
            }
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Could not load transactions: "
                + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

