    private void renumberCart(DefaultTableModel model) {
        for (int i = 0; i < model.getRowCount(); i++) {
            model.setValueAt(i + 1, i, 0);
        }
    }

    private double sumColumn(DefaultTableModel model, int column) {
        double total = 0;

        for (int i = 0; i < model.getRowCount(); i++) {
            Object value = model.getValueAt(i, column);

            if (value == null) {
                continue;
            }

            String raw = value.toString().trim().replace(",", "");

            if (raw.isEmpty()) {
                continue;
            }

            try {
                total += Double.parseDouble(raw);
            } catch (NumberFormatException ignored) {
                // Ignore empty or non-numeric cells.
            }
        }

        return total;
    }

    private void recalcSalesTotal() {
        DefaultTableModel model = (DefaultTableModel) salestable.getModel();
        double total = sumColumn(model, 6);
        salesfieldtotal.setText(MONEY.format(total));
        recalcSalesChange();
    }

    private void recalcSalesChange() {
        String totalText = salesfieldtotal.getText().trim().replace(",", "");
        String cashText = salesfieldcashamount.getText().trim().replace(",", "");
        if (totalText.isEmpty() || cashText.isEmpty()) {
            salesfieldchange.setText("");
            return;
        }
        try {
            double total = Double.parseDouble(totalText);
            double cash = Double.parseDouble(cashText);
            salesfieldchange.setText(MONEY.format(cash - total));
        } catch (NumberFormatException e) {
            salesfieldchange.setText("");
        }
    }

    /**
     * There is no dedicated "checkout" button on the Sales tab, so pressing
     * Enter inside the Cash Amount field finalizes the sale. Consider adding
     * a real "PAY"/"CHECKOUT" button in the Form Editor and wiring it here instead.
     */
    private void checkoutSale() {
        DefaultTableModel model = (DefaultTableModel) salestable.getModel();
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, "Cart is empty.");
            return;
        }
        double total = sumColumn(model, 6);
        double cash;
        try {
            cash = Double.parseDouble(salesfieldcashamount.getText().trim().replace(",", ""));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a valid cash amount.");
            return;
        }
        if (cash < total) {
            JOptionPane.showMessageDialog(this, "Cash amount is less than the total.");
            return;
        }
        double change = cash - total;

        Connection con = null;
        try {
            con = DBConnection.getConnection();
            con.setAutoCommit(false);

            // customer_id is NULL for a walk-in parts sale.
            PreparedStatement insertTrans = con.prepareStatement(
                    "INSERT INTO sales_transactions (customer_id, transaction_type, total_amount, amount_paid, change_amount) VALUES (NULL, 'Parts Sale', ?, ?, ?)",
                    Statement.RETURN_GENERATED_KEYS);
            insertTrans.setDouble(1, total);
            insertTrans.setDouble(2, cash);
            insertTrans.setDouble(3, change);
            insertTrans.executeUpdate();

            int transactionId;
            try (ResultSet keys = insertTrans.getGeneratedKeys()) {
                keys.next();
                transactionId = keys.getInt(1);
            }
            insertTrans.close();

            PreparedStatement insertItem = con.prepareStatement(
                    "INSERT INTO sales_transaction_items (transaction_id, product_id, quantity, unit_price, subtotal) VALUES (?, ?, ?, ?, ?)");
            // The "AND stock_quantity >= ?" guard stops the stock from going negative.
            PreparedStatement updateStock = con.prepareStatement(
                    "UPDATE products SET stock_quantity = stock_quantity - ? WHERE product_id = ? AND stock_quantity >= ?");

            for (int i = 0; i < model.getRowCount(); i++) {
                int productId = Integer.parseInt(model.getValueAt(i, 1).toString());
                double price = Double.parseDouble(model.getValueAt(i, 4).toString().replace(",", ""));
                int qty = Integer.parseInt(model.getValueAt(i, 5).toString());
                double subtotal = Double.parseDouble(model.getValueAt(i, 6).toString().replace(",", ""));

                insertItem.setInt(1, transactionId);
                insertItem.setInt(2, productId);
                insertItem.setInt(3, qty);
                insertItem.setDouble(4, price);
                insertItem.setDouble(5, subtotal);
                insertItem.addBatch();

                updateStock.setInt(1, qty);
                updateStock.setInt(2, productId);
                updateStock.setInt(3, qty);
                updateStock.addBatch();
            }
            insertItem.executeBatch();
            for (int updated : updateStock.executeBatch()) {
                if (updated == 0) {
                    throw new SQLException("Not enough stock for one of the items in the cart.");
                }
            }
            insertItem.close();
            updateStock.close();

            con.commit();

            java.util.List<String> receiptLines = new java.util.ArrayList<>();
            for (int i = 0; i < model.getRowCount(); i++) {
                String item = model.getValueAt(i, 2).toString();
                int qty = Integer.parseInt(model.getValueAt(i, 5).toString());
                double sub = Double.parseDouble(model.getValueAt(i, 6).toString().replace(",", ""));
                receiptLines.add(String.format("%-18s x%-3d %9.2f", item.length() > 18 ? item.substring(0, 18) : item, qty, sub));
            }
            JOptionPane.showMessageDialog(this, "Sale complete. Change: " + MONEY.format(change));
            int print = JOptionPane.showConfirmDialog(
        this,
        "Generate receipt PDF now?",
        "Receipt",
        JOptionPane.YES_NO_OPTION
);

if (print == JOptionPane.YES_OPTION) {
    try {

        String transactionNo =
                String.format("TXN-%08d", transactionId);

        java.io.File pdfFile = ReceiptPDF.generate(
                transactionNo,
                "Walk-in",
                receiptLines,
                total,
                cash,
                change
        );

        ReceiptPDF.open(pdfFile);

    } catch (Exception ex) {

        JOptionPane.showMessageDialog(
                this,
                "Unable to generate receipt PDF:\n\n"
                + ex.getMessage(),
                "Receipt PDF Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

            model.setRowCount(0);
            salesfieldtotal.setText("");
            salesfieldcashamount.setText("");
            salesfieldchange.setText("");
            loadProducts();
            loadTransactions(null, null, "All");

        } catch (SQLException | NumberFormatException e) {
            if (con != null) {
                try {
                    con.rollback();
                } catch (SQLException ignore) {
                }
            }
            JOptionPane.showMessageDialog(this, "Could not complete the sale: " + e.getMessage(),
                    "Database Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            if (con != null) {
                try {
                    con.setAutoCommit(true);
                    con.close();
                } catch (SQLException ignore) {
                }
            }
        }
    }

