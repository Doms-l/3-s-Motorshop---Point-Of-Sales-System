    /** Looks the product up by barcode (what the scanner types). A plain product ID also works as a fallback. */
    private void scanProductForSale() {
        String code = salesfieldscanproduct.getText().trim();
        if (code.isEmpty()) {
            return;
        }
        scannedProductId = -1;

        long idGuess = -1;
        try {
            idGuess = Long.parseLong(code);
        } catch (NumberFormatException ignored) {
            // not numeric -> barcode lookup only
        }

        String sql = "SELECT product_id, brand, product_name, unit_price FROM products "
                + "WHERE active = 1 AND (barcode = ? OR product_id = ?) "
                + "ORDER BY (barcode = ?) DESC LIMIT 1";
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, code);
            ps.setLong(2, idGuess);
            ps.setString(3, code);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    JOptionPane.showMessageDialog(this, "No product found for \"" + code + "\"");
                    salesfieldbrand.setText("");
                    salesfieldname.setText("");
                    salesfieldprice.setText("");
                    return;
                }
                scannedProductId = rs.getInt("product_id");
                String brand = rs.getString("brand");
                salesfieldbrand.setText(brand == null ? "" : brand);
                salesfieldname.setText(rs.getString("product_name"));
                salesfieldprice.setText(MONEY.format(rs.getDouble("unit_price")));
                salesfieldquantity.setText("1");
                salesfieldquantity.requestFocus();
                salesfieldquantity.selectAll();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
        }
    }

   private void addProductToCart() {

    String barcode = salesfieldscanproduct.getText().trim();

    if (barcode.isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Please enter or scan a product barcode first.",
                "Product Required",
                JOptionPane.WARNING_MESSAGE
        );
        salesfieldscanproduct.requestFocus();
        return;
    }

    String sql =
            "SELECT product_id, brand, product_name, unit_price, stock_quantity " +
            "FROM products " +
            "WHERE active = 1 AND barcode = ? " +
            "LIMIT 1";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setString(1, barcode);

        try (ResultSet rs = ps.executeQuery()) {

            // ---------------------------------------------------------
            // PRODUCT NOT FOUND
            // ---------------------------------------------------------
            if (!rs.next()) {

                JOptionPane.showMessageDialog(
                        this,
                        "No active product was found for barcode:\n" + barcode,
                        "Product Not Found",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            // ---------------------------------------------------------
            // GET PRODUCT INFORMATION
            // ---------------------------------------------------------
            int productId = rs.getInt("product_id");

            String brand = rs.getString("brand");
            String productName = rs.getString("product_name");

            double price = rs.getDouble("unit_price");
            int stock = rs.getInt("stock_quantity");

            // ---------------------------------------------------------
            // DISPLAY PRODUCT INFORMATION
            // ---------------------------------------------------------
            salesfieldbrand.setText(
                    brand == null ? "" : brand
            );

            salesfieldname.setText(
                    productName == null ? "" : productName
            );

            salesfieldprice.setText(
                    MONEY.format(price)
            );

            // ---------------------------------------------------------
            // READ QUANTITY
            // ---------------------------------------------------------
            String quantityText =
                    salesfieldquantity.getText().trim();

            if (quantityText.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "Please enter the quantity.",
                        "Quantity Required",
                        JOptionPane.WARNING_MESSAGE
                );

                salesfieldquantity.requestFocus();
                return;
            }

            int quantity;

            try {

                quantity = Integer.parseInt(quantityText);

            } catch (NumberFormatException e) {

                JOptionPane.showMessageDialog(
                        this,
                        "Quantity must be a whole number.",
                        "Invalid Quantity",
                        JOptionPane.WARNING_MESSAGE
                );

                salesfieldquantity.requestFocus();
                salesfieldquantity.selectAll();
                return;
            }

            // ---------------------------------------------------------
            // VALIDATE QUANTITY
            // ---------------------------------------------------------
            if (quantity <= 0) {

                JOptionPane.showMessageDialog(
                        this,
                        "Quantity must be greater than zero.",
                        "Invalid Quantity",
                        JOptionPane.WARNING_MESSAGE
                );

                salesfieldquantity.requestFocus();
                salesfieldquantity.selectAll();
                return;
            }

            // ---------------------------------------------------------
            // CHECK STOCK
            // ---------------------------------------------------------
            if (stock <= 0) {

                JOptionPane.showMessageDialog(
                        this,
                        "This product is out of stock.",
                        "Out of Stock",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            if (quantity > stock) {

                JOptionPane.showMessageDialog(
                        this,
                        "Not enough stock.\n\n"
                        + "Available stock: " + stock
                        + "\nRequested quantity: " + quantity,
                        "Insufficient Stock",
                        JOptionPane.WARNING_MESSAGE
                );

                salesfieldquantity.requestFocus();
                salesfieldquantity.selectAll();
                return;
            }

            // ---------------------------------------------------------
            // GET CART MODEL
            // ---------------------------------------------------------
            DefaultTableModel cart =
                    (DefaultTableModel) salestable.getModel();

            // ---------------------------------------------------------
            // CHECK IF PRODUCT IS ALREADY IN CART
            // ---------------------------------------------------------
            int alreadyInCart = 0;

            for (int i = 0; i < cart.getRowCount(); i++) {

                Object idValue = cart.getValueAt(i, 1);
                Object qtyValue = cart.getValueAt(i, 5);

                /*
                 * IMPORTANT:
                 * Skip empty rows.
                 *
                 * Your original table contained blank rows,
                 * which caused the NullPointerException.
                 */
                if (idValue == null || qtyValue == null) {
                    continue;
                }

                String idText = idValue.toString().trim();
                String qtyText = qtyValue.toString().trim();

                if (idText.isEmpty() || qtyText.isEmpty()) {
                    continue;
                }

                try {

                    int existingProductId =
                            Integer.parseInt(idText);

                    int existingQuantity =
                            Integer.parseInt(qtyText);

                    if (existingProductId == productId) {
                        alreadyInCart += existingQuantity;
                    }

                } catch (NumberFormatException ignored) {

                    /*
                     * Ignore malformed/empty rows rather than
                     * crashing the POS.
                     */
                }
            }

            // ---------------------------------------------------------
            // CHECK TOTAL QUANTITY AGAINST STOCK
            // ---------------------------------------------------------
            if (alreadyInCart + quantity > stock) {

                JOptionPane.showMessageDialog(
                        this,
                        "Not enough stock.\n\n"
                        + "Available stock: " + stock
                        + "\nAlready in cart: " + alreadyInCart
                        + "\nRequested: " + quantity,
                        "Insufficient Stock",
                        JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            // ---------------------------------------------------------
            // CALCULATE SUBTOTAL
            // ---------------------------------------------------------
            double subtotal = price * quantity;

            // ---------------------------------------------------------
            // ADD PRODUCT TO CART
            // ---------------------------------------------------------
            cart.addRow(new Object[]{
                cart.getRowCount() + 1,
                productId,
                brand,
                productName,
                MONEY.format(price),
                quantity,
                MONEY.format(subtotal)
            });

            // ---------------------------------------------------------
            // RECALCULATE TOTAL
            // ---------------------------------------------------------
            recalcSalesTotal();

            // ---------------------------------------------------------
            // CLEAR INPUT FIELDS
            // ---------------------------------------------------------
            clearScanFields();
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Database error while adding product:\n\n"
                + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

