    // One note per row of servicestable (same order), saved to service_records.notes at checkout.
    private final java.util.List<String> serviceNotes = new java.util.ArrayList<>();

    private void addServiceToCart() {
        String plate = serfeildmotorcycleplateno.getText().trim();
        String customer = serfeildcustomerowner.getText().trim();
        String type = (String) servicesComboBox.getSelectedItem();
        String feeText = serfieldservicefee.getText().trim().replace(",", "");

        if (type == null || type.trim().isEmpty() || type.equals("Select:") || plate.isEmpty() || customer.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Fill in plate no., customer, and service type.");
            return;
        }
        double fee;
        try {
            fee = Double.parseDouble(feeText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Service fee must be a number.");
            return;
        }

        String note = serfeildnote.getText().trim();
        if (note.length() > 200) {
            note = note.substring(0, 200);
        }
        serviceNotes.add(note);

        DefaultTableModel model = (DefaultTableModel) servicestable.getModel();
        model.addRow(new Object[]{model.getRowCount() + 1, plate, customer, type, MONEY.format(fee)});

        clearServiceFields();
        recalcServicesTotal();
    }

